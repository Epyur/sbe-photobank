/** Модалка «Справка»: подробная инструкция по работе с фотобанком. */
export class PhotobankHelpModal extends Modal {
  constructor(app: App) {
    super(app);
  }

  onOpen(): void {
    this.titleEl.setText('Справка: LogicTEAM.Фотобанк');
    const wrap = this.contentEl.createDiv({ cls: 'tn-card' });
    for (const section of HELP_SECTIONS) {
      const card = wrap.createDiv({ cls: 'tn-card tn-photo-help-section' });
      card.createDiv({ cls: 'tn-card-head' }).createEl('h3', { text: section.title });
      for (const p of section.body) {
        card.createDiv({ cls: 'tn-photo-help-text', text: p });
      }
    }
  }

  onClose(): void {
    this.contentEl.empty();
  }
}
